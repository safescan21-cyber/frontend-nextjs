const LANGS = ['fr', 'ja', 'ko'];
const build = (col) => {
  const out = Object.fromEntries(Object.entries(ROWS).map(([en, row]) => [en, row[col]]).filter(([, v]) => v));
  // Machine category titles and descriptions: same translations as their page titles
  for (const [slug, c] of Object.entries(PRODUCT_DATA)) {
    const row = SEO_TEXT[LANGS[col]]?.[`/products/${slug}`];
    if (row) {
      out[c.title] ??= row[0];
      out[c.description] ??= row[1];
    }
  }
  return out;
};

// Urdu has its own file (messagesUr.js), keyed the same way
const buildUr = () => {
  const out = { ...UR };
  for (const [slug, c] of Object.entries(PRODUCT_DATA)) {
    const row = SEO_TEXT.ur?.[`/products/${slug}`];
    if (row) {
      out[c.title] ??= row[0];
      out[c.description] ??= row[1];
    }
  }
  return out;
};

export const MESSAGES = { fr: build(0), ja: build(1), ko: build(2), ur: buildUr() };
