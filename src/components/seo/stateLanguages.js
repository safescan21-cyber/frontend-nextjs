// { lang, label, text, dir } for a state, or null
export const stateLocalNote = (slug) => {
  const row = STATES[slug];
  if (!row) return null;
  const [lang, name] = row;
  return { lang, label: TEXT[lang][0], text: TEXT[lang][1](name), dir: lang === 'ur' ? 'rtl' : 'ltr' };
};
